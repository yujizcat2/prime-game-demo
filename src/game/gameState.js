import {
  GAME_CONFIG
} from "./config";

import {
  FOOD_TYPES,
  FOOD_PURITY
} from "./rules";

import {
  createMazeHistory
} from "./mazeHistory";

import {
  BOARD_CONFIG,
  createEmptyBoard
} from "./boardRules";





// ============================================================
// 创建初始状态
//
// 新版开局：
//
// 荤   素   调料
// ·    ·    ·
// ·    ·    ·
//
// 初始三个棋子均视为原生食材。
//
// 因此：
//
// 荤   → pure
// 素   → pure
// 调料 → pure
//
// ------------------------------------------------------------
//
// collectionTypeHistory
//
// 只记录“首次新收藏”的真实 foodType 顺序。
//
// 例如：
//
// [
//   "seasoning",
//   "meat",
//   "vegetable",
//   "meat"
// ]
//
// 重复处理旧收藏时，不应追加。
//
// 当前 V1 只用于研究荤素失衡度。
// 暂时不产生任何惩罚。
// ------------------------------------------------------------
//
// mazeHistory
//
// 初始规则状态必须立即写入迷宫历史。
// ============================================================

export function createGameState(
  values
){


  const board =
    createEmptyBoard();



  const initialValues =

    Array.isArray(
      values
    )

      ?

        values.slice(
          0,
          3
        )

      :

        [];



  const initialFoodTypes = [

    FOOD_TYPES.MEAT,

    FOOD_TYPES.VEGETABLE,

    FOOD_TYPES.SEASONING

  ];



  initialValues.forEach(

    (
      value,
      index
    ) => {


      board[index] = {


        id:
          index + 1,


        value,


        foodType:

          initialFoodTypes[index]

          ??

          FOOD_TYPES.MEAT,


        purity:
          FOOD_PURITY.PURE,


        parents:
          null,


        parentFoods:
          null,


        origin:
          null

      };

    }

  );





  // ==========================================================
  // 基础状态
  // ==========================================================

  const baseState = {

    board,





    // ========================================================
    // 已收藏的不同数字
    // ========================================================

    collection:
      [],





    // ========================================================
    // 首次收藏类型历史
    //
    // 注意：
    //
    // 这里记录的是收藏发生时棋子的真实 foodType，
    // 不是根据数字推断类型。
    //
    // 只有“首次收藏”才会加入。
    // ========================================================

    collectionTypeHistory:
      [],





    // ========================================================
    // 收藏来源
    // ========================================================

    collectionOrigins:
      {},





    // ========================================================
    // 收藏路径
    // ========================================================

    collectionPaths:
      {},





    // ========================================================
    // 最新收藏
    // ========================================================

    latestCollection:
      null,





    // ========================================================
    // 分数
    // ========================================================

    score:
      0,





    // ========================================================
    // 正式步数
    // ========================================================

    steps:
      0,





    // ========================================================
    // 游戏结束
    // ========================================================

    gameOver:
      false,





    // ========================================================
    // 下一棋子 ID
    // ========================================================

    nextId:
      initialValues.length + 1,





    // ========================================================
    // 最近一次迷宫回转事件
    // ========================================================

    mazeTurn:
      null

  };





  // ==========================================================
  // 创建迷宫历史
  //
  // createMazeHistory 会立即记录开局 S0。
  // ==========================================================

  const mazeHistory =

    createMazeHistory(
      baseState
    );





  return {

    ...baseState,

    mazeHistory

  };

}





// ============================================================
// 消耗一个时间单位
// ============================================================

export function consumeStep(
  state
){


  return {

    ...state,

    steps:

      state.steps

      +

      GAME_CONFIG.STEP_COST

  };

}