import {
  gcd
} from "../utils/math";



// ============================================================
// 是否可以约分
// ============================================================

export function canReduce(
  a,
  b
) {


  return gcd(
    a.value,
    b.value
  ) > 1;

}





// ============================================================
// 判断合成后的数字
// ============================================================

export function combineValue(
  a,
  b
) {


  let value =
    a + b;


  while(
    value > 101
  ){

    value -= 100;

  }


  return value;

}





// ============================================================
// 判断合成后的动物
// ============================================================

export function combineAnimal(
  front,
  back
) {


  if(
    !front ||
    !back
  ){

    return null;

  }



  const sameAnimal =

    front.animal ===
    back.animal;



  const crossed101 =

    front.value +
    back.value >
    101;



  // ==========================================================
  // 不同动物
  // 永远以前面的动物为准
  // ==========================================================

  if(
    !sameAnimal
  ){

    return front.animal;

  }



  // ==========================================================
  // 相同动物
  // 没跨 101
  // ==========================================================

  if(
    !crossed101
  ){

    return front.animal;

  }



  // ==========================================================
  // 相同动物
  // 跨 101
  // 猫狗翻转
  // ==========================================================

  if(
    front.animal === "cat"
  ){

    return "dog";

  }


  if(
    front.animal === "dog"
  ){

    return "cat";

  }



  return front.animal;

}





// ============================================================
// 判断是否已经存在同父母孩子
// ============================================================

export function hasSameParents(
  numbers,
  a,
  b
) {


  return numbers.some(

    item => {


      if(
        !item.parents
      ){

        return false;

      }



      const p1 =
        item.parents[0];


      const p2 =
        item.parents[1];



      return (

        (
          p1 === a &&
          p2 === b
        )

        ||

        (
          p1 === b &&
          p2 === a
        )

      );

    }

  );

}





// ============================================================
// 判断两个数字之间是否存在“合成关系”
//
// 注意：
//
// 这个函数只判断数字关系本身。
// 不考虑棋盘有没有空位。
//
// 主要用于：
// 活性 / 潜在关系 / 局面评价
//
// ============================================================

export function canCombineRelation(
  a,
  b,
  numbers
) {


  // ==========================================================
  // 不能和自己的父母合成
  // ==========================================================

  if(
    a.parents &&
    a.parents.includes(
      b.value
    )
  ){

    return false;

  }



  if(
    b.parents &&
    b.parents.includes(
      a.value
    )
  ){

    return false;

  }



  // ==========================================================
  // 已存在同父母孩子
  // ==========================================================

  if(
    hasSameParents(
      numbers,
      a.value,
      b.value
    )
  ){

    return false;

  }



  return true;

}





// ============================================================
// 判断当前是否真的可以执行合成
//
// 与 canCombineRelation 不同：
//
// canCombineRelation
// → 数字之间有没有合成关系
//
// canCombine
// → 玩家现在能不能真的执行合成
//
// ============================================================

export function canCombine(
  a,
  b,
  numbers
) {


  // ==========================================================
  // 满 10 格
  // 禁止实际合成
  // ==========================================================

  if(
    numbers.length >= 10
  ){

    return false;

  }



  // ==========================================================
  // 再判断数字关系
  // ==========================================================

  return canCombineRelation(
    a,
    b,
    numbers
  );

}