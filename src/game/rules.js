import {
  gcd
} from "../utils/math";



// ============================================================
// 食物类型
//
// meat       = 荤系
// vegetable  = 素系
// seasoning  = 调料系
// dessert    = 甜食系
//
// 荤 / 素 / 调料
// 三种全部存在于主棋盘。
//
// dessert 为特殊类型。
// ============================================================

export const FOOD_TYPES = {

  MEAT:
    "meat",

  VEGETABLE:
    "vegetable",

  SEASONING:
    "seasoning",

  DESSERT:
    "dessert"

};





// ============================================================
// 是否可以约分
// ============================================================

export function canReduce(
  a,
  b
) {


  return gcd(
    a.value,
    b.value
  ) > 1;

}





// ============================================================
// 是否跨过101
//
// 判断原始相加值是否 > 101。
// ============================================================

export function isCrossing101(
  a,
  b
) {


  return (
    a + b > 101
  );

}





// ============================================================
// 判断合成后的数字
//
// 数学规则保持不变：
//
// a + b
//
// >101 时不断 -100
//
// 例如：
//
// 60 + 50 = 110
// → 10
//
// 101 + 101 = 202
// → 102
// → 2
// ============================================================

export function combineValue(
  a,
  b
) {


  let value =
    a + b;


  while(
    value > 101
  ){

    value -= 100;

  }


  return value;

}





// ============================================================
// 判断是否属于普通三系
//
// 普通三系：
//
// 荤
// 素
// 调料
//
// 甜食不属于普通三系。
// ============================================================

export function isNormalFoodType(
  foodType
) {


  return [

    FOOD_TYPES.MEAT,

    FOOD_TYPES.VEGETABLE,

    FOOD_TYPES.SEASONING

  ].includes(
    foodType
  );

}





// ============================================================
// 判断合成后的料理类型
//
// ============================================================
// 第一层：甜食规则
// ============================================================
//
// 甜食 + 荤
// → 荤
//
// 甜食 + 素
// → 素
//
// 甜食 + 调料
// → 调料
//
// 甜食 + 甜食
// → 甜食
//
//
// 注意：
//
// 上述规则不受是否跨101影响。
//
//
// 例如：
//
// 甜食60 + 荤50
// = 110
// → 数字10
// → 类型仍为荤
//
//
// 甜食60 + 甜食50
// = 110
// → 数字10
// → 类型仍为甜食
//
//
// ============================================================
// 第二层：普通跨101
// ============================================================
//
// 如果双方都属于：
//
// 荤 / 素 / 调料
//
// 并且原始相加值 > 101：
//
// → 统一进入甜食系
//
//
// 例如：
//
// 荤60 + 素50
// = 110
// → 数字10
// → 甜食10
//
//
// 调料80 + 调料40
// = 120
// → 数字20
// → 甜食20
//
//
// ============================================================
// 第三层：普通三循环
// ============================================================
//
// 只有在：
//
// 双方都是普通类型
//
// 并且：
//
// 没有跨101
//
// 时才进入普通三循环。
//
//
// 同类：
//
// 荤 + 荤
// → 荤
//
// 素 + 素
// → 素
//
// 调料 + 调料
// → 调料
//
//
// 异类：
//
// 荤 + 素
// → 调料
//
// 素 + 调料
// → 荤
//
// 调料 + 荤
// → 素
//
// ============================================================

export function combineFoodType(
  front,
  back
) {


  if(
    !front ||
    !back
  ){

    return null;

  }



  const frontType =
    front.foodType;


  const backType =
    back.foodType;



  if(
    !frontType ||
    !backType
  ){

    return null;

  }



  // ==========================================================
  // 1. 甜食 + 甜食
  //
  // 无论是否跨101：
  //
  // → 甜食
  // ==========================================================

  if(
    frontType === FOOD_TYPES.DESSERT &&
    backType === FOOD_TYPES.DESSERT
  ){


    return FOOD_TYPES.DESSERT;

  }



  // ==========================================================
  // 2. 甜食 + 普通
  //
  // 结果继承普通类型。
  //
  // 无论是否跨101。
  // ==========================================================

  if(
    frontType === FOOD_TYPES.DESSERT &&
    isNormalFoodType(
      backType
    )
  ){


    return backType;

  }



  if(
    backType === FOOD_TYPES.DESSERT &&
    isNormalFoodType(
      frontType
    )
  ){


    return frontType;

  }



  // ==========================================================
  // 3. 到这里以后
  //
  // 正常情况下双方都应该属于普通三系。
  // ==========================================================

  const bothNormal =

    isNormalFoodType(
      frontType
    )

    &&

    isNormalFoodType(
      backType
    );



  if(
    !bothNormal
  ){


    return null;

  }



  // ==========================================================
  // 4. 普通 + 普通
  //
  // 如果跨101：
  //
  // → 甜食
  //
  // 这是甜食第一次进入棋盘的主要入口。
  // ==========================================================

  const crossed101 =

    isCrossing101(

      front.value,

      back.value

    );



  if(
    crossed101
  ){


    return FOOD_TYPES.DESSERT;

  }



  // ==========================================================
  // 5. 普通同类
  //
  // 未跨101：
  //
  // 荤 + 荤
  // → 荤
  //
  // 素 + 素
  // → 素
  //
  // 调料 + 调料
  // → 调料
  // ==========================================================

  if(
    frontType === backType
  ){


    return frontType;

  }



  // ==========================================================
  // 6. 荤 + 素
  //
  // → 调料
  //
  // 顺序无关。
  // ==========================================================

  if(
    (
      frontType === FOOD_TYPES.MEAT &&
      backType === FOOD_TYPES.VEGETABLE
    )
    ||
    (
      frontType === FOOD_TYPES.VEGETABLE &&
      backType === FOOD_TYPES.MEAT
    )
  ){


    return FOOD_TYPES.SEASONING;

  }



  // ==========================================================
  // 7. 素 + 调料
  //
  // → 荤
  //
  // 顺序无关。
  // ==========================================================

  if(
    (
      frontType === FOOD_TYPES.VEGETABLE &&
      backType === FOOD_TYPES.SEASONING
    )
    ||
    (
      frontType === FOOD_TYPES.SEASONING &&
      backType === FOOD_TYPES.VEGETABLE
    )
  ){


    return FOOD_TYPES.MEAT;

  }



  // ==========================================================
  // 8. 调料 + 荤
  //
  // → 素
  //
  // 顺序无关。
  // ==========================================================

  if(
    (
      frontType === FOOD_TYPES.SEASONING &&
      backType === FOOD_TYPES.MEAT
    )
    ||
    (
      frontType === FOOD_TYPES.MEAT &&
      backType === FOOD_TYPES.SEASONING
    )
  ){


    return FOOD_TYPES.VEGETABLE;

  }



  // ==========================================================
  // 非法 / 未知类型
  // ==========================================================

  return null;

}





// ============================================================
// 判断是否已经存在同父母孩子
// ============================================================

export function hasSameParents(
  numbers,
  a,
  b
) {


  return numbers.some(

    item => {


      if(
        !item.parents
      ){

        return false;

      }



      const p1 =
        item.parents[0];


      const p2 =
        item.parents[1];



      return (

        (
          p1 === a &&
          p2 === b
        )

        ||

        (
          p1 === b &&
          p2 === a
        )

      );

    }

  );

}





// ============================================================
// 判断两个数字之间是否存在“合成关系”
//
// 这个函数只判断数字关系本身。
// 不考虑棋盘有没有空位。
// ============================================================

export function canCombineRelation(
  a,
  b,
  numbers
) {


  // ==========================================================
  // 不能和自己的父母合成
  // ==========================================================

  if(
    a.parents &&
    a.parents.includes(
      b.value
    )
  ){

    return false;

  }



  if(
    b.parents &&
    b.parents.includes(
      a.value
    )
  ){

    return false;

  }



  // ==========================================================
  // 已存在同父母孩子
  // ==========================================================

  if(
    hasSameParents(
      numbers,
      a.value,
      b.value
    )
  ){

    return false;

  }



  return true;

}





// ============================================================
// 判断当前是否真的可以执行合成
//
// 当前主棋盘为九宫格。
// ============================================================

export function canCombine(
  a,
  b,
  numbers
) {


  // ==========================================================
  // 满9格禁止实际合成
  // ==========================================================

  if(
    numbers.length >= 9
  ){

    return false;

  }



  return canCombineRelation(
    a,
    b,
    numbers
  );

}