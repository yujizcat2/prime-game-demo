// ============================================================
// 食物类型
//
// meat      = 荤系
// vegetable = 素系
// dessert   = 甜食系 / 当前高阶系
//
// seasoning 不属于主菜盘类型，
// 它存在于独立 seasoningTray。
// ============================================================

export const FOOD_TYPES = {

  MEAT:
    "meat",

  VEGETABLE:
    "vegetable",

  DESSERT:
    "dessert"

};





// ============================================================
// 是否可以约分
// ============================================================

export function canReduce(
  a,
  b
) {


  return gcd(
    a.value,
    b.value
  ) > 1;

}





// ============================================================
// 是否跨过101
//
// 注意：
//
// 这里判断的是“原始相加值”。
// 不是经过 -100 处理后的结果。
// ============================================================

export function isCrossing101(
  a,
  b
) {


  return (
    a + b > 101
  );

}





// ============================================================
// 判断合成后的数字
//
// 原数学规则保持不变：
//
// a + b
//
// >101 时不断 -100
//
// 例如：
//
// 60 + 50 = 110
// → 10
//
// 101 + 101 = 202
// → 102
// → 2
// ============================================================

export function combineValue(
  a,
  b
) {


  let value =
    a + b;


  while(
    value > 101
  ){

    value -= 100;

  }


  return value;

}





// ============================================================
// 判断合成后的料理类型
//
// 核心规则：
//
// 1. 没跨101
//    → 主菜盘位置靠前者决定结果类型
//
// 2. 跨101
//    → 统一进入甜食系 dessert
//
// 例如：
//
// 荤12 在前 + 素17
// → 荤29
//
// 素17 在前 + 荤12
// → 素29
//
// 荤60 在前 + 素50
// → 110跨101
// → 甜食10
//
// 甜食30 在前 + 荤20
// → 甜食50
//
// 荤20 在前 + 甜食30
// → 荤50
//
// ============================================================
//
// 【暂时规则】
//
// 如果 dessert 作为前位再次跨101，
// 目前仍然保持 dessert。
//
// 等以后设计“二次质变”时，
// 只需要在这里继续增加判断。
// ============================================================

export function combineFoodType(
  front,
  back
) {


  if(
    !front ||
    !back
  ){

    return null;

  }



  const crossed101 =

    isCrossing101(
      front.value,
      back.value
    );



  // ==========================================================
  // 跨101
  //
  // 当前统一进入甜食系
  // ==========================================================

  if(
    crossed101
  ){


    return FOOD_TYPES.DESSERT;

  }



  // ==========================================================
  // 没跨101
  //
  // 谁在主菜盘位置靠前，
  // 就继承谁的类型。
  // ==========================================================

  return (
    front.foodType
    ??
    null
  );

}





// ============================================================
// 判断是否已经存在同父母孩子
// ============================================================

export function hasSameParents(
  numbers,
  a,
  b
) {


  return numbers.some(

    item => {


      if(
        !item.parents
      ){

        return false;

      }



      const p1 =
        item.parents[0];


      const p2 =
        item.parents[1];



      return (

        (
          p1 === a &&
          p2 === b
        )

        ||

        (
          p1 === b &&
          p2 === a
        )

      );

    }

  );

}





// ============================================================
// 判断两个数字之间是否存在“合成关系”
//
// 注意：
//
// 这个函数只判断数字关系本身。
// 不考虑棋盘有没有空位。
//
// 主要用于：
// 活性 / 潜在关系 / 局面评价
// ============================================================

export function canCombineRelation(
  a,
  b,
  numbers
) {


  // ==========================================================
  // 不能和自己的父母合成
  // ==========================================================

  if(
    a.parents &&
    a.parents.includes(
      b.value
    )
  ){

    return false;

  }



  if(
    b.parents &&
    b.parents.includes(
      a.value
    )
  ){

    return false;

  }



  // ==========================================================
  // 已存在同父母孩子
  // ==========================================================

  if(
    hasSameParents(
      numbers,
      a.value,
      b.value
    )
  ){

    return false;

  }



  return true;

}





// ============================================================
// 判断当前是否真的可以执行合成
//
// canCombineRelation
// → 数字之间有没有合成关系
//
// canCombine
// → 玩家现在能不能真的执行合成
// ============================================================

export function canCombine(
  a,
  b,
  numbers
) {


  // ==========================================================
  // 满10格
  // 禁止实际合成
  // ==========================================================

  if(
    numbers.length >= 10
  ){

    return false;

  }



  return canCombineRelation(
    a,
    b,
    numbers
  );

}