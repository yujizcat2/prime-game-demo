import {
  canCombine,
  canCombineRelation,
  canReduce,
  combineValue
} from "./rules";

import {
  isPrime
} from "./prime";



// ============================================================
// 容量压力
//
// 棋盘越接近满格，
// 未来变化空间越小。
//
// 9格与10格都视为临界区，
// 避免 9 → 10 时活性突然断崖。
// ============================================================

function getCapacityFactor(
  count
) {


  if(
    count <= 5
  ){

    return 1;

  }


  if(
    count === 6
  ){

    return 0.9;

  }


  if(
    count === 7
  ){

    return 0.8;

  }


  if(
    count === 8
  ){

    return 0.7;

  }


  // 9格 / 10格
  return 0.50;

}





// ============================================================
// 获取棋盘活性
//
// 活性现在由三层组成：
//
// 1. 数字之间存在多少潜在关系
// 2. 质密对关系质量的影响
// 3. 棋盘容量压力
//
// 注意：
//
// “合法动作”与“活性”已经不是同一个东西。
//
// 合法动作：
// 玩家现在真的可以执行什么
//
// 活性：
// 当前棋盘还蕴含多少继续变化的潜力
//
// ============================================================

export function getActivityStatus(
  numbers = [],
  primeDensity = 0
) {


  // ==========================================================
  // 质密安全处理
  // ==========================================================

  const density =

    Math.max(
      0,
      Math.min(
        100,
        Number(
          primeDensity
        ) || 0
      )
    );



  // ==========================================================
  // 质密系数
  //
  // 0%   → 1.00
  // 100% → 0.50
  // ==========================================================

  const densityFactor =

    1 -
    0.5 *
    (
      density /
      100
    );



  // ==========================================================
  // 动作基础权重
  // ==========================================================

  // 合成得到普通结果
  const normalCombineWeight =
    densityFactor;


  // 合成得到质数
  const primeCombineWeight =

    0.5 *
    densityFactor;


  // 约分受质密影响较小
  const reduceWeight =

    0.8 +
    0.2 *
    densityFactor;



  // ==========================================================
  // 空棋盘
  // ==========================================================

  if(
    !Array.isArray(numbers) ||
    numbers.length === 0
  ){

    return {

      activity: 0,

      activityScore: 0,

      activityMax: 0,


      legal: 0,

      total: 0,


      combineLegal: 0,

      combinePotential: 0,

      combineTotal: 0,

      combineActivity: 0,


      combinePrimeLegal: 0,

      combineNormalLegal: 0,


      reduceLegal: 0,

      reduceTotal: 0,

      reduceActivity: 0,


      removeLegal: 0,


      pairCount: 0,

      capacityFactor: 1,

      densityFactor,


      dead: true

    };

  }



  // ==========================================================
  // 当前棋盘数字数量
  // ==========================================================

  const count =
    numbers.length;



  // ==========================================================
  // 容量系数
  // ==========================================================

  const capacityFactor =

    getCapacityFactor(
      count
    );



  // ==========================================================
  // 数字对数量
  //
  // C(n,2)
  // ==========================================================

  const pairCount =

    count *
    (count - 1) /
    2;



  // ==========================================================
  // 理论动作数量
  // ==========================================================

  const combineTotal =
    pairCount;


  const reduceTotal =
    pairCount;


  const total =

    combineTotal +
    reduceTotal;



  // ==========================================================
  // 理论最大活性
  //
  // 每对：
  //
  // 合成 1
  // 约分 1
  // ==========================================================

  const activityMax =

    pairCount *
    2;



  // ==========================================================
  // 当前真实合法动作
  // ==========================================================

  let combineLegal = 0;

  let reduceLegal = 0;



  // ==========================================================
  // 潜在合成关系
  // ==========================================================

  let combinePotential = 0;



  // ==========================================================
  // 合成结果分类
  // ==========================================================

  let combinePrimeLegal = 0;

  let combineNormalLegal = 0;



  // ==========================================================
  // 活性
  // ==========================================================

  let combineActivity = 0;

  let reduceActivity = 0;



  // ==========================================================
  // 遍历所有数字对
  // ==========================================================

  for(
    let i = 0;
    i < numbers.length;
    i++
  ){


    for(
      let j = i + 1;
      j < numbers.length;
      j++
    ){


      const first =
        numbers[i];


      const second =
        numbers[j];



      // ======================================================
      // 真实可执行合成
      //
      // 10格时这里一定为 false
      // ======================================================

      if(
        canCombine(
          first,
          second,
          numbers
        )
      ){

        combineLegal++;

      }



      // ======================================================
      // 潜在合成关系
      //
      // 即使10格，
      // 这里仍然继续计算。
      // ======================================================

      if(
        canCombineRelation(
          first,
          second,
          numbers
        )
      ){


        combinePotential++;



        const result =

          combineValue(
            first.value,
            second.value
          );



        // ====================================================
        // 合成后得到质数
        // ====================================================

        if(
          isPrime(
            result
          )
        ){


          combinePrimeLegal++;


          combineActivity +=
            primeCombineWeight;


        }



        // ====================================================
        // 合成后得到非质数
        // ====================================================

        else{


          combineNormalLegal++;


          combineActivity +=
            normalCombineWeight;


        }


      }



      // ======================================================
      // 约分
      // ======================================================

      if(
        canReduce(
          first,
          second
        )
      ){


        reduceLegal++;


        reduceActivity +=
          reduceWeight;


      }


    }

  }



  // ==========================================================
  // 当前棋盘上的 1
  //
  // 不参与活性，
  // 但参与死局判断。
  // ==========================================================

  const removeLegal =

    numbers.filter(

      item =>
        item.value === 1

    ).length;



  // ==========================================================
  // 当前真正合法动作数量
  //
  // 注意：
  //
  // 满10格以后，
  // combineLegal = 0
  // ==========================================================

  const legal =

    combineLegal +
    reduceLegal;



  // ==========================================================
  // 潜在关系活性
  //
  // 先计算数字关系本身，
  // 再统一受到容量压力影响。
  // ==========================================================

  const potentialActivity =

    combineActivity +
    reduceActivity;



  // ==========================================================
  // 最终有效活性
  //
  // 潜在活性 × 容量系数
  // ==========================================================

  const activityScore =

    potentialActivity *
    capacityFactor;



  // ==========================================================
  // 活性百分比
  // ==========================================================

  const activity =

    activityMax === 0

      ? 0

      : Math.round(

          (
            activityScore /
            activityMax *
            100
          ) *
          10

        ) / 10;



  // ==========================================================
  // 死局
  //
  // 必须使用真实合法动作，
  // 不能使用潜在合成关系。
  // ==========================================================

  const dead =

    combineLegal === 0 &&
    reduceLegal === 0 &&
    removeLegal === 0;



  // ==========================================================
  // 返回
  // ==========================================================

  return {

    // ========================
    // 最终活性
    // ========================

    activity,

    activityScore,

    activityMax,

    potentialActivity,


    // ========================
    // 真实动作
    // ========================

    legal,

    total,


    // ========================
    // 合成
    // ========================

    combineLegal,

    combinePotential,

    combineTotal,

    combineActivity,


    combinePrimeLegal,

    combineNormalLegal,


    // ========================
    // 约分
    // ========================

    reduceLegal,

    reduceTotal,

    reduceActivity,


    // ========================
    // 1
    // ========================

    removeLegal,


    // ========================
    // 环境参数
    // ========================

    pairCount,

    primeDensity:
      density,

    densityFactor,

    capacityFactor,


    // ========================
    // 当前权重
    // ========================

    normalCombineWeight,

    primeCombineWeight,

    reduceWeight,


    // ========================
    // 死局
    // ========================

    dead

  };

}