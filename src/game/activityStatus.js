import {
  canCombine,
  canReduce
} from "./rules";



// ============================================================
// 棋盘活性状态
//
// 活性 =
//
// 当前合法动作数
// ---------------- × 100
// 当前理论动作数
//
// 动作类型：
// 1. 合成
// 2. 约分
// 3. 消除 1
//
// 同一对数字如果既可以合成又可以约分，
// 视为两个不同的合法动作。
// ============================================================

export function getActivityStatus(
  numbers = []
) {


  // ==========================================================
  // 空棋盘
  // ==========================================================

  if(
    !Array.isArray(numbers) ||
    numbers.length === 0
  ){

    return {

      activity: 0,

      legal: 0,

      total: 0,


      combineLegal: 0,

      combineTotal: 0,


      reduceLegal: 0,

      reduceTotal: 0,


      removeLegal: 0,

      removeTotal: 0,


      pairCount: 0,

      dead: true

    };

  }



  // ==========================================================
  // 当前数字数量
  // ==========================================================

  const count =
    numbers.length;



  // ==========================================================
  // 数字对总数
  //
  // C(n, 2)
  // ==========================================================

  const pairCount =

    count *
    (count - 1) /
    2;



  // ==========================================================
  // 理论动作数
  // ==========================================================

  const combineTotal =
    pairCount;


  const reduceTotal =
    pairCount;



  // ==========================================================
  // 合法动作计数
  // ==========================================================

  let combineLegal = 0;

  let reduceLegal = 0;



  // ==========================================================
  // 遍历棋盘上的所有数字对
  // ==========================================================

  for(
    let i = 0;
    i < numbers.length;
    i++
  ){


    for(
      let j = i + 1;
      j < numbers.length;
      j++
    ){


      const first =
        numbers[i];


      const second =
        numbers[j];



      // ======================================================
      // 合成
      //
      // 直接复用 rules.js
      // 保证和真正游戏规则一致
      // ======================================================

      if(
        canCombine(
          first,
          second,
          numbers
        )
      ){

        combineLegal++;

      }



      // ======================================================
      // 约分
      // ======================================================

      if(
        canReduce(
          first,
          second
        )
      ){

        reduceLegal++;

      }


    }

  }



  // ==========================================================
  // 消除 1
  //
  // 一个 1 = 一个合法消除动作
  // ==========================================================

  const removeLegal =

    numbers.filter(

      item =>
        item.value === 1

    ).length;



  // ==========================================================
  // 当前定义：
  //
  // 只有实际存在的 1
  // 才形成一个理论消除动作
  // ==========================================================

  const removeTotal =
    removeLegal;



  // ==========================================================
  // 总合法动作
  // ==========================================================

  const legal =

    combineLegal +
    reduceLegal +
    removeLegal;



  // ==========================================================
  // 总理论动作
  // ==========================================================

  const total =

    combineTotal +
    reduceTotal +
    removeTotal;



  // ==========================================================
  // 活性百分比
  // ==========================================================

  const activity =

    total === 0

      ? 0

      : Math.round(

          legal /
          total *
          100

        );



  // ==========================================================
  // 死局
  // ==========================================================

  const dead =
    legal === 0;



  // ==========================================================
  // 返回
  // ==========================================================

  return {

    activity,


    legal,

    total,


    combineLegal,

    combineTotal,


    reduceLegal,

    reduceTotal,


    removeLegal,

    removeTotal,


    pairCount,


    dead

  };

}