import {
  canCombine,
  canReduce,
  combineValue
} from "./rules";

import {
  isPrime
} from "./prime";



// ============================================================
// 获取棋盘活性状态
//
// 活性由两个因素决定：
//
// 1. 当前到底有多少合法动作
// 2. 每个合法动作本身的“活性价值”
//
// ------------------------------------------------------------
//
// 质密越高：
//
// - 合成活性下降明显
// - 合成出质数进一步降低
// - 约分只受到轻微影响
//
// ------------------------------------------------------------
//
// 质密系数：
//
// densityFactor
// = 1 - 0.5 × (primeDensity / 100)
//
// 质密 0   → 1.00
// 质密 20  → 0.90
// 质密 40  → 0.80
// 质密 60  → 0.70
// 质密 80  → 0.60
// 质密 100 → 0.50
//
// ============================================================

export function getActivityStatus(
  numbers = [],
  primeDensity = 0
) {


  // ==========================================================
  // 安全处理质密
  // ==========================================================

  const density =

    Math.max(
      0,
      Math.min(
        100,
        Number(
          primeDensity
        ) || 0
      )
    );



  // ==========================================================
  // 质密影响系数
  // ==========================================================

  const densityFactor =

    1 -
    0.5 *
    (
      density /
      100
    );



  // ==========================================================
  // 当前各类动作权重
  // ==========================================================

  // 普通合成
  const normalCombineWeight =
    densityFactor;


  // 合成后得到质数
  const primeCombineWeight =

    0.5 *
    densityFactor;


  // 约分
  //
  // 约分本身通常能够帮助棋盘重新产生变化，
  // 所以不应该被高质密压得太低。
  const reduceWeight =

    0.8 +
    0.2 *
    densityFactor;



  // ==========================================================
  // 空棋盘
  // ==========================================================

  if(
    !Array.isArray(numbers) ||
    numbers.length === 0
  ){

    return {

      activity: 0,

      activityScore: 0,

      activityMax: 0,


      legal: 0,

      total: 0,


      combineLegal: 0,

      combineTotal: 0,

      combineActivity: 0,


      combinePrimeLegal: 0,

      combineNormalLegal: 0,


      reduceLegal: 0,

      reduceTotal: 0,

      reduceActivity: 0,


      removeLegal: 0,


      pairCount: 0,


      primeDensity: density,

      densityFactor,


      normalCombineWeight,

      primeCombineWeight,

      reduceWeight,


      dead: true

    };

  }



  // ==========================================================
  // 当前棋盘数字数量
  // ==========================================================

  const count =
    numbers.length;



  // ==========================================================
  // 数字对总数
  //
  // C(n, 2)
  // ==========================================================

  const pairCount =

    count *
    (count - 1) /
    2;



  // ==========================================================
  // 理论动作数量
  // ==========================================================

  const combineTotal =
    pairCount;


  const reduceTotal =
    pairCount;


  const total =

    combineTotal +
    reduceTotal;



  // ==========================================================
  // 理论最大活性
  //
  // 这里故意不根据质密降低。
  //
  // 原因：
  //
  // 高质密本身就应该让实际活性降低。
  //
  // 每一对数字理论最高：
  //
  // 合成 +1
  // 约分 +1
  //
  // ==========================================================

  const activityMax =

    pairCount *
    2;



  // ==========================================================
  // 动作计数
  // ==========================================================

  let combineLegal = 0;

  let reduceLegal = 0;


  let combinePrimeLegal = 0;

  let combineNormalLegal = 0;



  // ==========================================================
  // 活性累计
  // ==========================================================

  let combineActivity = 0;

  let reduceActivity = 0;



  // ==========================================================
  // 遍历所有数字对
  // ==========================================================

  for(
    let i = 0;
    i < numbers.length;
    i++
  ){


    for(
      let j = i + 1;
      j < numbers.length;
      j++
    ){


      const first =
        numbers[i];


      const second =
        numbers[j];



      // ======================================================
      // 合成
      //
      // canCombine 内部应已经包含：
      //
      // numbers.length >= 10
      // → false
      // ======================================================

      if(
        canCombine(
          first,
          second,
          numbers
        )
      ){


        combineLegal++;



        // ====================================================
        // 合成结果
        // ====================================================

        const result =

          combineValue(
            first.value,
            second.value
          );



        // ====================================================
        // 合成后为质数
        // ====================================================

        if(
          isPrime(
            result
          )
        ){


          combinePrimeLegal++;


          combineActivity +=
            primeCombineWeight;


        }



        // ====================================================
        // 合成后不是质数
        // ====================================================

        else{


          combineNormalLegal++;


          combineActivity +=
            normalCombineWeight;


        }


      }



      // ======================================================
      // 约分
      // ======================================================

      if(
        canReduce(
          first,
          second
        )
      ){


        reduceLegal++;


        reduceActivity +=
          reduceWeight;


      }


    }

  }



  // ==========================================================
  // 当前棋盘上的 1
  //
  // 只用于死局判断，
  // 不参与活性计算。
  // ==========================================================

  const removeLegal =

    numbers.filter(

      item =>
        item.value === 1

    ).length;



  // ==========================================================
  // 合法关系动作数量
  // ==========================================================

  const legal =

    combineLegal +
    reduceLegal;



  // ==========================================================
  // 实际有效活性
  // ==========================================================

  const activityScore =

    combineActivity +
    reduceActivity;



  // ==========================================================
  // 活性百分比
  //
  // 保留 1 位小数
  // ==========================================================

  const activity =

    activityMax === 0

      ? 0

      : Math.round(

          (
            activityScore /
            activityMax *
            100
          ) *
          10

        ) / 10;



  // ==========================================================
  // 死局
  // ==========================================================

  const dead =

    combineLegal === 0 &&
    reduceLegal === 0 &&
    removeLegal === 0;



  // ==========================================================
  // 返回
  // ==========================================================

  return {

    // ========================
    // 核心活性
    // ========================

    activity,

    activityScore,

    activityMax,


    // ========================
    // 动作数量
    // ========================

    legal,

    total,


    // ========================
    // 合成
    // ========================

    combineLegal,

    combineTotal,

    combineActivity,


    combinePrimeLegal,

    combineNormalLegal,


    // ========================
    // 约分
    // ========================

    reduceLegal,

    reduceTotal,

    reduceActivity,


    // ========================
    // 消除 1
    // ========================

    removeLegal,


    // ========================
    // 棋盘结构
    // ========================

    pairCount,


    // ========================
    // 质密相关
    // ========================

    primeDensity:
      density,

    densityFactor,

    normalCombineWeight,

    primeCombineWeight,

    reduceWeight,


    // ========================
    // 死局
    // ========================

    dead

  };

}