import {
  canCombine,
  canCombineRelation,
  canReduce,
  combineValue
} from "./rules";

import {
  isPrime
} from "./prime";



// ============================================================
// 容量活性系数
//
// 0格 / 1格 → 0.00
// 2格       → 0.35
// 3格       → 0.55
// 4格       → 0.75
// 5格       → 0.95
// 6格       → 1.00
// 7格       → 0.90
// 8格       → 0.70
// 9格       → 0.50
// 10格      → 0.50
//
// 数字太少：
// 关系不足，活性低。
//
// 中间区域：
// 关系丰富，同时还有扩展空间，
// 活性最高。
//
// 接近满盘：
// 容量压力增大，活性下降。
// ============================================================

function getCapacityFactor(
  count
) {


  // ==========================================================
  // 0格 / 1格
  // 无法形成数字对
  // ==========================================================

  if(
    count <= 1
  ){

    return 0;

  }



  // ==========================================================
  // 2格
  // ==========================================================

  if(
    count === 2
  ){

    return 0.35;

  }



  // ==========================================================
  // 3格
  // ==========================================================

  if(
    count === 3
  ){

    return 0.55;

  }



  // ==========================================================
  // 4格
  // ==========================================================

  if(
    count === 4
  ){

    return 0.75;

  }



  // ==========================================================
  // 5格
  // ==========================================================

  if(
    count === 5
  ){

    return 0.95;

  }



  // ==========================================================
  // 6格
  //
  // 当前设定中的理想活跃区
  // ==========================================================

  if(
    count === 6
  ){

    return 1;

  }



  // ==========================================================
  // 7格
  // ==========================================================

  if(
    count === 7
  ){

    return 0.9;

  }



  // ==========================================================
  // 8格
  //
  // 警戒线
  // ==========================================================

  if(
    count === 8
  ){

    return 0.7;

  }



  // ==========================================================
  // 9格 / 10格
  //
  // 高容量压力
  // ==========================================================

  return 0.5;

}





// ============================================================
// 获取棋盘活性
//
// 活性由以下因素共同决定：
//
// 1. 数字之间存在多少潜在关系
// 2. 合成后是否得到质数
// 3. 当前质密
// 4. 当前数字数量所带来的容量压力
// 5. 满盘以后合成通道被锁定
//
// ------------------------------------------------------------
//
// 合法动作 ≠ 活性
//
// 合法动作：
// 玩家此刻真正能执行的动作数量。
//
// 活性：
// 当前棋盘整体继续变化的潜力。
// ============================================================

export function getActivityStatus(
  numbers = [],
  primeDensity = 0
) {


  // ==========================================================
  // 质密安全处理
  // ==========================================================

  const density =

    Math.max(
      0,
      Math.min(
        100,
        Number(
          primeDensity
        ) || 0
      )
    );



  // ==========================================================
  // 质密系数
  //
  // 质密 0%
  // → 1.00
  //
  // 质密 100%
  // → 0.50
  // ==========================================================

  const densityFactor =

    1 -
    0.5 *
    (
      density /
      100
    );



  // ==========================================================
  // 当前动作权重
  // ==========================================================

  // 普通合成
  const normalCombineWeight =
    densityFactor;


  // 合成后得到质数
  const primeCombineWeight =

    0.5 *
    densityFactor;


  // 约分
  //
  // 约分通常能够重新打开棋盘，
  // 因此受到质密的影响较小。
  const reduceWeight =

    0.8 +
    0.2 *
    densityFactor;



  // ==========================================================
  // 空棋盘
  // ==========================================================

  if(
    !Array.isArray(numbers) ||
    numbers.length === 0
  ){

    return {

      activity: 0,

      activityScore: 0,

      activityMax: 0,

      potentialActivity: 0,


      legal: 0,

      total: 0,


      combineLegal: 0,

      combinePotential: 0,

      combineTotal: 0,

      combineActivity: 0,


      combinePrimeLegal: 0,

      combineNormalLegal: 0,


      reduceLegal: 0,

      reduceTotal: 0,

      reduceActivity: 0,


      removeLegal: 0,


      pairCount: 0,


      primeDensity:
        density,

      densityFactor,

      capacityFactor: 0,

      blockedCombineFactor: 1,


      normalCombineWeight,

      primeCombineWeight,

      reduceWeight,


      dead: true

    };

  }



  // ==========================================================
  // 当前数字数量
  // ==========================================================

  const count =
    numbers.length;



  // ==========================================================
  // 当前容量活性系数
  // ==========================================================

  const capacityFactor =

    getCapacityFactor(
      count
    );



  // ==========================================================
  // 满盘合成残余系数
  //
  // 未满盘：
  // 潜在合成关系正常计算。
  //
  // 10格满盘：
  // 实际合成无法执行，
  // 所以潜在合成只保留15%的价值。
  // ==========================================================

  const blockedCombineFactor =

    count >= 10

      ? 0.15

      : 1;



  // ==========================================================
  // 数字对数量
  //
  // C(n,2)
  // ==========================================================

  const pairCount =

    count *
    (count - 1) /
    2;



  // ==========================================================
  // 理论动作数量
  // ==========================================================

  const combineTotal =
    pairCount;


  const reduceTotal =
    pairCount;


  const total =

    combineTotal +
    reduceTotal;



  // ==========================================================
  // 理论最大活性
  //
  // 每一对理论最高：
  //
  // 合成 +1
  // 约分 +1
  // ==========================================================

  const activityMax =

    pairCount *
    2;



  // ==========================================================
  // 当前真实合法动作
  // ==========================================================

  let combineLegal = 0;

  let reduceLegal = 0;



  // ==========================================================
  // 潜在合成关系
  // ==========================================================

  let combinePotential = 0;



  // ==========================================================
  // 合成结果分类
  // ==========================================================

  let combinePrimeLegal = 0;

  let combineNormalLegal = 0;



  // ==========================================================
  // 活性累计
  // ==========================================================

  let combineActivity = 0;

  let reduceActivity = 0;



  // ==========================================================
  // 遍历所有数字对
  // ==========================================================

  for(
    let i = 0;
    i < numbers.length;
    i++
  ){


    for(
      let j = i + 1;
      j < numbers.length;
      j++
    ){


      const first =
        numbers[i];


      const second =
        numbers[j];



      // ======================================================
      // 当前真实可执行合成
      //
      // 满10格时，
      // canCombine 应返回 false。
      // ======================================================

      if(
        canCombine(
          first,
          second,
          numbers
        )
      ){

        combineLegal++;

      }



      // ======================================================
      // 潜在合成关系
      //
      // 不考虑棋盘是否满格。
      // ======================================================

      if(
        canCombineRelation(
          first,
          second,
          numbers
        )
      ){


        combinePotential++;



        // ====================================================
        // 合成结果
        // ====================================================

        const result =

          combineValue(
            first.value,
            second.value
          );



        // ====================================================
        // 合成后得到质数
        // ====================================================

        if(
          isPrime(
            result
          )
        ){


          combinePrimeLegal++;


          combineActivity +=
            primeCombineWeight;


        }



        // ====================================================
        // 合成后得到非质数
        // ====================================================

        else{


          combineNormalLegal++;


          combineActivity +=
            normalCombineWeight;


        }


      }



      // ======================================================
      // 约分
      // ======================================================

      if(
        canReduce(
          first,
          second
        )
      ){


        reduceLegal++;


        reduceActivity +=
          reduceWeight;


      }


    }

  }



  // ==========================================================
  // 当前棋盘上的1
  //
  // 消除1不参与活性计算，
  // 但参与死局判断。
  // ==========================================================

  const removeLegal = 0;



  // ==========================================================
  // 当前真实合法动作数量
  //
  // 不包含消除1。
  // ==========================================================

  const legal =

    combineLegal +
    reduceLegal;



  // ==========================================================
  // 潜在关系活性
  //
  // 未满盘：
  //
  // 合成活性
  // +
  // 约分活性
  //
  //
  // 满盘：
  //
  // 合成活性 × 0.15
  // +
  // 约分活性
  // ==========================================================

  const potentialActivity =

    combineActivity *
    blockedCombineFactor

    +

    reduceActivity;



  // ==========================================================
  // 最终有效活性
  //
  // 潜在活性
  // ×
  // 容量系数
  //
  // 于是形成：
  //
  // 1格 → 0%
  // 2～5格 → 逐渐上升
  // 6格 → 高峰
  // 7格以后 → 逐渐受到容量压力
  // 8格 → 警戒
  // 9～10格 → 高压区域
  // ==========================================================

  const activityScore =

    potentialActivity *
    capacityFactor;



  // ==========================================================
  // 最终活性百分比
  //
  // 保留1位小数
  // ==========================================================

  const activity =

    activityMax === 0

      ? 0

      : Math.round(

          (
            activityScore /
            activityMax *
            100
          ) *
          10

        ) / 10;



  // ==========================================================
  // 死局
  //
  // 必须根据真实可执行动作判断。
  // ==========================================================

  const dead =

    combineLegal === 0 &&
    reduceLegal === 0;



  // ==========================================================
  // 返回
  // ==========================================================

  return {

    // ========================
    // 最终活性
    // ========================

    activity,

    activityScore,

    activityMax,

    potentialActivity,


    // ========================
    // 当前真实动作
    // ========================

    legal,

    total,


    // ========================
    // 合成
    // ========================

    combineLegal,

    combinePotential,

    combineTotal,

    combineActivity,


    combinePrimeLegal,

    combineNormalLegal,


    // ========================
    // 约分
    // ========================

    reduceLegal,

    reduceTotal,

    reduceActivity,


    // ========================
    // 消除1
    // ========================

    removeLegal,


    // ========================
    // 棋盘
    // ========================

    pairCount,


    // ========================
    // 环境系数
    // ========================

    primeDensity:
      density,

    densityFactor,

    capacityFactor,

    blockedCombineFactor,


    // ========================
    // 当前动作权重
    // ========================

    normalCombineWeight,

    primeCombineWeight,

    reduceWeight,


    // ========================
    // 死局
    // ========================

    dead

  };

}
