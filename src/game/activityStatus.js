import {
  canCombine,
  canReduce,
  combineValue
} from "./rules";

import {
  isPrime
} from "./prime";



// ============================================================
// 活性权重
// ============================================================

const ACTIVITY_WEIGHT = {

  // 合成后是普通合数
  COMBINE_NORMAL: 1,

  // 合成后是质数
  COMBINE_PRIME: 0.5,

  // 合法约分
  REDUCE: 1,

};



// ============================================================
// 获取棋盘活性状态
//
// 活性不再只是：
// 合法动作数 / 理论动作数
//
// 而是：
//
// 当前所有合法动作的活性权重
// -------------------------- × 100
// 当前棋盘理论最大活性权重
//
// ------------------------------------------------------------
//
// 合成：
//
// 合成后为合数
// +1
//
// 合成后为质数
// +0.5
//
// ------------------------------------------------------------
//
// 约分：
//
// 每个合法约分
// +1
//
// ------------------------------------------------------------
//
// 消除 1：
//
// 不参与活性计算
//
// 因为活性主要衡量
// 当前数字之间继续发生变化的能力
//
// ============================================================

export function getActivityStatus(
  numbers = []
) {


  // ==========================================================
  // 空棋盘
  // ==========================================================

  if(
    !Array.isArray(numbers) ||
    numbers.length === 0
  ){

    return {

      // 最终活性百分比
      activity: 0,

      // 实际活性值
      activityScore: 0,

      // 理论最大活性值
      activityMax: 0,


      // 合法动作数量
      legal: 0,

      // 理论动作数量
      total: 0,


      // 合成
      combineLegal: 0,

      combineTotal: 0,

      combineActivity: 0,


      // 其中：
      // 合成后为质数
      combinePrimeLegal: 0,

      // 合成后为合数
      combineNormalLegal: 0,


      // 约分
      reduceLegal: 0,

      reduceTotal: 0,

      reduceActivity: 0,


      // 消除
      // 仅作为信息返回
      // 不计入活性
      removeLegal: 0,


      pairCount: 0,

      dead: true

    };

  }



  // ==========================================================
  // 当前数字数量
  // ==========================================================

  const count =
    numbers.length;



  // ==========================================================
  // 所有数字对数量
  //
  // C(n, 2)
  // ==========================================================

  const pairCount =

    count *
    (count - 1) /
    2;



  // ==========================================================
  // 理论动作数量
  //
  // 每一对：
  //
  // 1 个理论合成
  // 1 个理论约分
  // ==========================================================

  const combineTotal =
    pairCount;


  const reduceTotal =
    pairCount;


  const total =

    combineTotal +
    reduceTotal;



  // ==========================================================
  // 理论最大活性
  //
  // 假设：
  //
  // 所有合成都得到最高权重 1
  // 所有约分都得到权重 1
  //
  // 因此：
  //
  // pairCount × 2
  // ==========================================================

  const activityMax =

    pairCount *
    2;



  // ==========================================================
  // 合法动作计数
  // ==========================================================

  let combineLegal = 0;

  let reduceLegal = 0;



  // ==========================================================
  // 合成分类
  // ==========================================================

  let combinePrimeLegal = 0;

  let combineNormalLegal = 0;



  // ==========================================================
  // 活性值
  // ==========================================================

  let combineActivity = 0;

  let reduceActivity = 0;



  // ==========================================================
  // 遍历所有数字对
  // ==========================================================

  for(
    let i = 0;
    i < numbers.length;
    i++
  ){


    for(
      let j = i + 1;
      j < numbers.length;
      j++
    ){


      const first =
        numbers[i];


      const second =
        numbers[j];



      // ======================================================
      // 合成
      // ======================================================

      if(
        canCombine(
          first,
          second,
          numbers
        )
      ){


        combineLegal++;



        // ====================================================
        // 计算合成结果
        // ====================================================

        const result =

          combineValue(
            first.value,
            second.value
          );



        // ====================================================
        // 合成后是质数
        //
        // 活性 +0.5
        // ====================================================

        if(
          isPrime(
            result
          )
        ){


          combinePrimeLegal++;


          combineActivity +=

            ACTIVITY_WEIGHT
              .COMBINE_PRIME;


        }



        // ====================================================
        // 合成后不是质数
        //
        // 活性 +1
        // ====================================================

        else{


          combineNormalLegal++;


          combineActivity +=

            ACTIVITY_WEIGHT
              .COMBINE_NORMAL;


        }


      }



      // ======================================================
      // 约分
      //
      // 每个合法约分
      // 活性 +1
      // ======================================================

      if(
        canReduce(
          first,
          second
        )
      ){


        reduceLegal++;


        reduceActivity +=

          ACTIVITY_WEIGHT
            .REDUCE;


      }


    }

  }



  // ==========================================================
  // 当前棋盘上的 1
  //
  // 只统计
  // 不计入活性
  // ==========================================================

  const removeLegal =

    numbers.filter(

      item =>
        item.value === 1

    ).length;



  // ==========================================================
  // 总合法关系动作数量
  //
  // 不包含消除 1
  // ==========================================================

  const legal =

    combineLegal +
    reduceLegal;



  // ==========================================================
  // 当前实际活性值
  // ==========================================================

  const activityScore =

    combineActivity +
    reduceActivity;



  // ==========================================================
  // 活性百分比
  //
  // 保留 1 位小数
  //
  // 例如：
  //
  // 4.5 / 12
  // = 37.5%
  // ==========================================================

  const activity =

    activityMax === 0

      ? 0

      : Math.round(

          (
            activityScore /
            activityMax *
            100
          ) *
          10

        ) / 10;



  // ==========================================================
  // 死局
  //
  // 这里把 1 的消除也算作
  // “仍然存在操作”
  //
  // 因此只有：
  //
  // 合成 = 0
  // 约分 = 0
  // 1 = 0
  //
  // 才是真正死局
  // ==========================================================

  const dead =

    combineLegal === 0 &&
    reduceLegal === 0 &&
    removeLegal === 0;



  // ==========================================================
  // 返回完整活性状态
  // ==========================================================

  return {

    // ========================
    // 核心活性
    // ========================

    activity,

    activityScore,

    activityMax,


    // ========================
    // 动作数量
    // ========================

    legal,

    total,


    // ========================
    // 合成
    // ========================

    combineLegal,

    combineTotal,

    combineActivity,


    combinePrimeLegal,

    combineNormalLegal,


    // ========================
    // 约分
    // ========================

    reduceLegal,

    reduceTotal,

    reduceActivity,


    // ========================
    // 1
    // ========================

    removeLegal,


    // ========================
    // 其他
    // ========================

    pairCount,

    dead

  };

}