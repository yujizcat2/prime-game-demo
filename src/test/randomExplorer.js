import {
  createSimulationState,
  getSimulationLegalActions,
  applySimulationAction
} from "./simulationEngine";



// ============================================================
// 随机探路测试
//
// 高速版：
//
// Random AI 本身只做一件事：
//
// 从当前所有合法动作中
// 随机选择一个动作。
//
// 所有游戏规则全部交给
// simulationEngine。
//
// 不使用正式 gameEngine，
// 因此不会生成：
//
// origin
// collectionOrigins
// collectionPaths
// latestCollection
// score
// UI历史
//
// 用于：
//
// 100局
// 1000局
// 10000局
// 100000局
// ============================================================





// ============================================================
// 随机生成开局
//
// 与当前正式游戏一致：
//
// 从 2～9 中
// 随机选择 3 个不同数字。
//
// simulationEngine 会自动赋予：
//
// 第1个 → 狗
// 第2个 → 猫
// 第3个 → 哺乳
// ============================================================

function createRandomInitialValues(){


  const pool = [

    2,
    3,
    4,
    5,
    6,
    7,
    8,
    9

  ];



  // Fisher-Yates
  for(
    let i = pool.length - 1;
    i > 0;
    i--
  ){


    const j =

      Math.floor(

        Math.random() *
        (
          i + 1
        )

      );



    const temp =
      pool[i];


    pool[i] =
      pool[j];


    pool[j] =
      temp;

  }



  return pool.slice(
    0,
    3
  );

}





// ============================================================
// 随机选择一个动作
// ============================================================

function randomChoice(
  actions
){


  const index =

    Math.floor(

      Math.random() *
      actions.length

    );



  return actions[
    index
  ];

}





// ============================================================
// 让浏览器刷新
//
// 注意：
//
// 只在批次之间调用。
// 单局内部完全不 await。
// ============================================================

function yieldToBrowser(){


  return new Promise(

    resolve => {


      window.setTimeout(

        resolve,

        0

      );

    }

  );

}





// ============================================================
// 随机玩一局
//
// 这是最核心的随机 AI。
//
// 流程：
//
// 开局
// ↓
// 获取合法动作
// ↓
// 随机选一个
// ↓
// 执行
// ↓
// 再获取合法动作
// ↓
// ...
// ↓
// 无合法动作
// ↓
// 游戏结束
//
// maxActions 只是测试保护阀。
// 不是正式游戏步数限制。
// ============================================================

export function runRandomGame({

  maxActions = 1000

} = {}){


  // ==========================================================
  // 随机开局
  // ==========================================================

  const initialValues =

    createRandomInitialValues();



  // ==========================================================
  // 创建轻量模拟状态
  // ==========================================================

  const state =

    createSimulationState(
      initialValues
    );



  // ==========================================================
  // 实际操作次数
  //
  // 与 steps 不一样。
  //
  // 因为：
  //
  // combine → actions +1 / steps +1
  // reduce  → actions +1 / steps +1
  // remove1 → actions +1 / steps +0
  // ==========================================================

  let actions =
    0;



  // ==========================================================
  // 开始随机探路
  // ==========================================================

  while(
    actions <
    maxActions
  ){


    // ========================================================
    // 当前所有合法动作
    // ========================================================

    const legalActions =

      getSimulationLegalActions(
        state
      );



    // ========================================================
    // 没有任何合法动作
    //
    // 本局自然结束。
    // ========================================================

    if(
      legalActions.length === 0
    ){


      break;

    }



    // ========================================================
    // 随机选择一个合法动作
    // ========================================================

    const action =

      randomChoice(
        legalActions
      );



    // ========================================================
    // 执行动作
    //
    // simulationEngine 原地修改 state，
    // 不创建新的完整 state。
    // ========================================================

    applySimulationAction(

      state,

      action

    );



    actions++;

  }





  // ==========================================================
  // 收藏 Set → Array
  //
  // 只在一局结束以后转换一次。
  // ==========================================================

  const collection =

    Array.from(
      state.collection
    );





  // ==========================================================
  // 返回单局结果
  // ==========================================================

  return {

    initialValues,



    // ========================================================
    // 正式游戏步数
    //
    // remove 1 不计。
    // ========================================================

    steps:
      state.steps,



    // ========================================================
    // AI总操作次数
    // ========================================================

    actions,



    // ========================================================
    // 收藏
    // ========================================================

    collection,



    collectionCount:
      state.collection.size,



    // ========================================================
    // 是否达到测试保护上限
    //
    // 如果这里为 true，
    // 说明这一局没有自然结束，
    // 数据需要特别观察。
    // ========================================================

    hitLimit:

      actions >=
      maxActions

  };

}





// ============================================================
// 批量随机探路
//
// games:
//
// 要测试多少局。
//
//
// maxActionsPerGame:
//
// 单局最大操作保护阀。
//
//
// batchSize:
//
// 每跑多少局刷新一次UI。
//
// 例如：
//
// games = 100000
// batchSize = 1000
//
// 浏览器只刷新约100次。
// ============================================================

export async function runRandomExplorer({

  games = 100,

  maxActionsPerGame = 1000,

  batchSize = 1000,

  onProgress = null

} = {}){


  // ==========================================================
  // 参数保护
  // ==========================================================

  const safeGames =

    Math.max(

      1,

      Math.floor(
        games
      )

    );



  const safeBatchSize =

    Math.max(

      1,

      Math.floor(
        batchSize
      )

    );





  // ==========================================================
  // 总步数
  // ==========================================================

  let totalSteps =
    0;



  // ==========================================================
  // 总收藏数
  // ==========================================================

  let totalCollection =
    0;





  // ==========================================================
  // 当前最长步数
  // ==========================================================

  let maxSteps =
    0;



  // ==========================================================
  // 当前最多收藏
  // ==========================================================

  let maxCollection =
    0;





  // ==========================================================
  // 最长步数纪录
  // ==========================================================

  let bestStepGame =
    null;





  // ==========================================================
  // 最多收藏纪录
  // ==========================================================

  let bestCollectionGame =
    null;





  // ==========================================================
  // 达到保护上限次数
  // ==========================================================

  let hitLimitCount =
    0;





  // ==========================================================
  // 开始批量测试
  // ==========================================================

  for(
    let gameIndex = 0;
    gameIndex < safeGames;
    gameIndex++
  ){


    // ========================================================
    // 全速跑完一局
    // ========================================================

    const result =

      runRandomGame({

        maxActions:
          maxActionsPerGame

      });





    // ========================================================
    // 累计步数
    // ========================================================

    totalSteps +=
      result.steps;





    // ========================================================
    // 累计收藏
    // ========================================================

    totalCollection +=
      result.collectionCount;





    // ========================================================
    // 最长步数纪录
    // ========================================================

    if(
      result.steps >
      maxSteps
    ){


      maxSteps =
        result.steps;



      bestStepGame = {

        gameIndex:
          gameIndex + 1,

        ...result

      };

    }





    // ========================================================
    // 最多收藏纪录
    // ========================================================

    if(
      result.collectionCount >
      maxCollection
    ){


      maxCollection =
        result.collectionCount;



      bestCollectionGame = {

        gameIndex:
          gameIndex + 1,

        ...result

      };

    }





    // ========================================================
    // 保护上限
    // ========================================================

    if(
      result.hitLimit
    ){


      hitLimitCount++;

    }





    // ========================================================
    // 批量刷新
    // ========================================================

    const completed =
      gameIndex + 1;



    const shouldYield =

      completed %
      safeBatchSize === 0

      ||

      completed ===
      safeGames;



    if(
      shouldYield
    ){


      // ======================================================
      // 更新TestLab
      // ======================================================

      if(
        typeof onProgress ===
        "function"
      ){


        onProgress({

          completed,

          total:
            safeGames,

          maxSteps,

          maxCollection,

          hitLimitCount

        });

      }



      // ======================================================
      // 把控制权还给浏览器
      // ======================================================

      await yieldToBrowser();

    }

  }





  // ==========================================================
  // 最终统计
  // ==========================================================

  return {

    games:
      safeGames,



    // ========================================================
    // 平均步数
    // ========================================================

    averageSteps:

      totalSteps /
      safeGames,



    // ========================================================
    // 最长步数
    // ========================================================

    maxSteps,



    // ========================================================
    // 平均收藏
    // ========================================================

    averageCollection:

      totalCollection /
      safeGames,



    // ========================================================
    // 最多收藏
    // ========================================================

    maxCollection,



    // ========================================================
    // 保护上限命中
    // ========================================================

    hitLimitCount,



    // ========================================================
    // 两项纪录
    // ========================================================

    bestStepGame,

    bestCollectionGame

  };

}